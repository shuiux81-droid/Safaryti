export function slugifyArticleHeading(text, usedIdsMap) {
  const cleaned = String(text || '')
    .trim()
    .toLowerCase()
    .replace(/[^\u0621-\u064A\u0660-\u0669\u0671-\u06D3a-z0-9\s-]/g, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
  const base = cleaned ? 'sec-' + cleaned : 'sec-heading';
  if (!usedIdsMap) return base;
  let candidate = base;
  let suffix = 2;
  while (usedIdsMap[candidate]) {
    candidate = base + '-' + suffix;
    suffix += 1;
  }
  usedIdsMap[candidate] = true;
  return candidate;
}
